package main

import (
	"fmt"
	"sort"
	"strings"
)

func pct(v *float64) string {
	if v == nil {
		return "-"
	}
	return fmt.Sprintf("%.3f", *v)
}

func renderMarkdown(r *Report) string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	w("# %s\n\n", r.Banner)
	if !r.Meaningful {
		w("> **These numbers only prove that the harness mechanics work** (dataset, embeddings, cosine sweep, pgvector GetNearest sweep, agreement check).\n")
		w("> They are not semantic-cache quality: %s.\n", r.NotMeaningfulWhy)
		w("> Do not quote the precision, recall or F1 below as how well the cache performs. Run with a real embedding model for that (see README, Part 2).\n\n")
	} else {
		w("> Real embeddings, but a small hand-written dataset (%d pairs, %d should-hit and %d hard negatives). Treat the numbers as indicative.\n\n", r.Pairs, r.Positives, r.Negatives)
	}
	w("Generated by `cachequality` (eval-harness). Started %s, finished %s.\n\n", r.StartedAt, r.FinishedAt)
	w("Command: `%s`\n\n", strings.Join(r.Command, " "))
	w("| | |\n|---|---|\n")
	w("| Embedder | %s |\n", r.Embedder)
	w("| Text embedded | %s |\n", map[string]string{"chat": "`user: <lowercased prompt>`, as the semantic cache builds it for a one-message chat request", "raw": "the prompt as written"}[r.TextFormat])
	w("| Dimension | %d |\n", r.Dimension)
	w("| Dataset | `%s`: %d pairs (%d should hit, %d should miss) |\n", r.Dataset, r.Pairs, r.Positives, r.Negatives)
	w("| Store check | %s |\n", r.Store)
	if r.StoreServer != nil {
		w("| PostgreSQL / pgvector | %v / %v |\n", r.StoreServer["server_version"], r.StoreServer["pgvector_version"])
	}
	if r.TotalDecisions > 0 {
		w("| Store vs cosine | %d of %d decisions agree (pairs x thresholds); max abs(store score - cosine) = %.1e |\n", r.AgreeingDecisions, r.TotalDecisions, r.MaxScoreAbsError)
	}
	w("| Best F1 (cosine) | %.3f at threshold %s |\n", r.BestF1, joinFloats(r.BestF1Thresholds))

	w("\n## Threshold sweep\n\n")
	w("Hit = similarity >= threshold. True hit: should-hit pair served from cache. False hit: hard negative served the wrong cached answer. False miss: paraphrase not served. True miss: hard negative correctly not served.\n\n")
	w("| Threshold | True hits | False hits | False misses | True misses | Precision | Recall | F1 | Store (GetNearest): TH / FH / FM / TM | Store agrees |\n")
	w("|---:|---:|---:|---:|---:|---:|---:|---:|---|---|\n")
	for _, row := range r.Thresholds {
		c := row.Cosine
		store, agree := "-", "-"
		if row.Store != nil {
			s := row.Store
			store = fmt.Sprintf("%d / %d / %d / %d", s.TrueHits, s.FalseHits, s.FalseMisses, s.TrueMisses)
			agree = "yes"
			if row.Disagreements > 0 {
				agree = fmt.Sprintf("NO (%d)", row.Disagreements)
			}
		}
		w("| %.2f | %d | %d | %d | %d | %s | %s | %.3f | %s | %s |\n", row.Threshold, c.TrueHits, c.FalseHits, c.FalseMisses, c.TrueMisses, pct(c.Precision), pct(c.Recall), c.F1, store, agree)
	}

	w("\n## Similarity by label\n\n| Label | Pairs | min | p25 | median | p75 | max |\n|---|---:|---:|---:|---:|---:|---:|\n")
	for _, label := range []string{"hit", "miss"} {
		if s, ok := r.SimilarityByLabel[label]; ok {
			name := map[string]string{"hit": "should hit (paraphrases)", "miss": "should miss (hard negatives)"}[label]
			w("| %s | %d | %.3f | %.3f | %.3f | %.3f | %.3f |\n", name, s.Count, s.Min, s.P25, s.Median, s.P75, s.Max)
		}
	}

	if len(r.Disagreements) > 0 {
		w("\n## Store and cosine disagreements\n\n| Pair | Threshold | Cosine | Store hit | Store score |\n|---|---:|---:|---|---:|\n")
		for _, d := range r.Disagreements {
			w("| %s | %.2f | %.6f | %v | %s |\n", d.Pair, d.Threshold, d.Cosine, d.StoreHit, pct(d.StoreScore))
		}
	}

	pairs := append([]PairResult(nil), r.PairResults...)
	sort.Slice(pairs, func(i, j int) bool { return pairs[i].Similarity > pairs[j].Similarity })
	w("\n## Every pair, by similarity\n\n<details><summary>%d pairs</summary>\n\n| Cosine | Label | Pair | a (cached) | b (incoming) |\n|---:|---|---|---|---|\n", len(pairs))
	for _, p := range pairs {
		w("| %.3f | %s | %s | %s | %s |\n", p.Similarity, p.Label, p.ID, cell(p.A), cell(p.B))
	}
	w("\n</details>\n")
	if !r.Meaningful {
		w("\n---\n\n**%s.** %s.\n", r.Banner, strings.ToUpper(r.NotMeaningfulWhy[:1])+r.NotMeaningfulWhy[1:])
	}
	return b.String()
}

func cell(s string) string { return strings.ReplaceAll(s, "|", "/") }

func joinFloats(values []float64) string {
	parts := make([]string, len(values))
	for i, v := range values {
		parts[i] = fmt.Sprintf("%.2f", v)
	}
	if len(parts) == 0 {
		return "-"
	}
	return strings.Join(parts, ", ")
}
