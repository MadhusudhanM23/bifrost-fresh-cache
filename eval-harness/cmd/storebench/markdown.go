func fmtMs(v float64) string {
	switch {
	case v == 0:
		return "0"
	case v < 1:
		return fmt.Sprintf("%.3f", v)
	case v < 100:
		return fmt.Sprintf("%.2f", v)
	default:
		return fmt.Sprintf("%.1f", v)
	}
}

func fmtBytes(v any) string {
	var n float64
	switch x := v.(type) {
	case int64:
		n = float64(x)
	case uint64:
		n = float64(x)
	case float64:
		n = x
	case int:
		n = float64(x)
	default:
		return fmt.Sprint(v)
	}
	switch {
	case n >= 1<<30:
		return fmt.Sprintf("%.2f GiB", n/(1<<30))
	case n >= 1<<20:
		return fmt.Sprintf("%.1f MiB", n/(1<<20))
	case n >= 1<<10:
		return fmt.Sprintf("%.1f KiB", n/(1<<10))
	}
	return fmt.Sprintf("%.0f B", n)
}

func correctnessText(op string, t *Tally) string {
	if t == nil || t.Executions == 0 {
		return "-"
	}
	var parts []string
	switch op {
	case opChunkHit:
		parts = append(parts, fmt.Sprintf("found and intact %d/%d", t.CorrectTop1, t.ExpectedResult))
	case opChunkMiss:
		parts = append(parts, fmt.Sprintf("not found %d/%d", t.CorrectEmpty, t.ExpectedEmpty))
	default:
		if t.ExpectedResult > 0 {
			parts = append(parts, fmt.Sprintf("recall@1 %.3f (%d/%d)", float64(t.CorrectTop1)/float64(t.ExpectedResult), t.CorrectTop1, t.ExpectedResult))
		}
		if t.ExpectedEmpty > 0 {
			parts = append(parts, fmt.Sprintf("false hits %d/%d", t.UnexpectedResult, t.ExpectedEmpty))
		}
		if t.CorrectTop1 > 0 {
			parts = append(parts, fmt.Sprintf("max score err %.1e", t.MaxScoreAbsError))
		}
	}
	extras := []struct {
		label string
		value int
	}{
		{"missed", t.MissedResult}, {"wrong top-1", t.WrongTop1}, {"filter violations", t.FilterViolations},
		{"below threshold", t.BelowThreshold}, {"unknown ids", t.UnknownIDs}, {"missing fields", t.MissingFields},
	}
	for _, e := range extras {
		if e.value > 0 {
			parts = append(parts, fmt.Sprintf("%s %d", e.label, e.value))
		}
	}
	return strings.Join(parts, "; ")
}

func renderMarkdown(r *Report) string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	env := r.Environment

	w("# Store benchmark results: `%s`\n\n", r.Config.Label)
	if !r.Complete {
		w("> **Incomplete:** this file was written while the run was still in progress or after it stopped early.\n\n")
	}
	w("Generated by `storebench` (eval-harness). Started %s, finished %s.\n\n", r.StartedAt, orDash(r.FinishedAt))
	w("Command: `%s`\n\n", strings.Join(r.Command, " "))

	w("## Environment\n\n| | |\n|---|---|\n")
	w("| Client (where the harness ran) | %s |\n", env.ClientLocation)
	w("| Client OS | %s %s |\n", env.OS, env.Kernel)
	w("| CPU | %s (%d logical CPUs visible to the client) |\n", env.CPUModel, env.LogicalCPUs)
	if env.MemoryBytes > 0 {
		w("| Memory visible to the client | %s |\n", fmtBytes(env.MemoryBytes))
	}
	w("| Go | %s %s/%s |\n", env.GoVersion, env.GOOS, env.GOARCH)
	w("| Latency clock | %s, median step %.0f ns |\n", env.ClockSource, env.ClockResolutionNs)
	if v, ok := env.Docker["server_version"]; ok {
		w("| Docker | server %v; %v |\n", v, env.Docker["engine"])
	} else if v, ok := env.Docker["cli"]; ok {
		w("| Docker | %v |\n", v)
	}
	if containers, ok := asStringMap(env.Docker["containers"]); ok {
		for _, name := range sortedKeys(containers) {
			w("| Container `%s` | %s |\n", name, containers[name])
		}
	}
	for _, res := range r.Results {
		if res.Server == nil {
			continue
		}
		switch res.Backend {
		case "pgvector":
			settings, _ := res.Server["settings"].(map[string]any)
			w("| PostgreSQL / pgvector (D=%d run) | %v / pgvector %v; synchronous_commit=%v, fsync=%v, shared_buffers=%v, hnsw.ef_search=%v, hnsw.max_scan_tuples=%v; at start: %v |\n",
				res.Dim, res.Server["server_version"], res.Server["pgvector_version"], settings["synchronous_commit"], settings["fsync"], settings["shared_buffers"], settings["hnsw.ef_search"], settings["hnsw.max_scan_tuples"], res.Server["other_sessions_at_start"])
		case "qdrant":
			w("| Qdrant (D=%d run) | %v (commit %v) |\n", res.Dim, res.Server["version"], res.Server["commit"])
		case "redis":
			w("| Redis (D=%d run) | %v, modules %v |\n", res.Dim, res.Server["redis_version"], res.Server["modules"])
		}
	}
	if code := env.CodeUnderTest; code != nil {
		if head, ok := code["git_head"]; ok {
			w("| Bifrost source | %v |\n", head)
		}
		if fp, ok := asStringMap(code["build_fingerprint"]); ok {
			w("| Compiled sources (sha256 prefix, stamped at build) | pgvector.go %s, qdrant.go %s, store.go %s; same as the files on disk at run time: %v |\n", fp["pgvector.go"], fp["qdrant.go"], fp["store.go"], code["build_matches_disk"])
		} else if fp, ok := code["build_fingerprint"].(string); ok {
			w("| Compiled sources | %s |\n", fp)
		}
		if files, ok := asStringMap(code["framework/vectorstore"]); ok {
			w("| pgvector.go / qdrant.go on disk at run time | %s / %s |\n", files["pgvector.go"], files["qdrant.go"])
		}
		if changes, ok := asStringSlice(code["uncommitted_vectorstore_changes"]); ok {
			w("| Uncommitted vectorstore changes | %s |\n", strings.Join(changes, ", "))
		}
	}
	for _, k := range sortedKeys(env.Notes) {
		w("| Note: %s | %s |\n", k, env.Notes[k])
	}

	c := r.Config
	w("\n## Workload\n\n")
	partition := c.N / c.Keys
	w("- N=%d entries per namespace, K=%d cache keys (each GetNearest filter selects ~%d entries), threshold %.2f, response payload %d bytes, seed %d.\n", c.N, c.Keys, partition, c.Threshold, c.ResponseBytes, c.Seed)
	w("- Writes: %d measured Add calls per (run, concurrency) after a preload; queries: %d measured operations per phase after %d warm-up operations; %d runs; concurrency %v.\n", c.WriteSample, c.Queries, c.Warmup, c.Runs, c.Concurrency)
	w("- Numbers below are the **median across runs** of each statistic. Latencies in milliseconds.\n")

	dims := []int{}
	seen := map[int]bool{}
	for _, res := range r.Results {
		if !seen[res.Dim] {
			seen[res.Dim] = true
			dims = append(dims, res.Dim)
		}
	}
	ops := append([]string{opAdd}, r.Config.Ops...)
	for _, dim := range dims {
		w("\n## Results, D=%d\n\n", dim)
		w("| Operation | Conc | Backend | p50 | p95 | p99 | mean | ops/s | errors | p50 min..max over runs | correctness (all runs at this concurrency) |\n")
		w("|---|---:|---|---:|---:|---:|---:|---:|---:|---|---|\n")
		for _, op := range ops {
			for _, conc := range r.Config.Concurrency {
				for _, res := range r.Results {
					if res.Dim != dim {
						continue
					}
					if res.Failure != "" && len(res.Medians) == 0 {
						continue
					}
					for _, m := range res.Medians {
						if m.Op != op || m.Concurrency != conc {
							continue
						}
						t := &Tally{}
						for _, p := range res.Phases {
							if p.Op == op && p.Concurrency == conc {
								t.merge(p.Correctness)
							}
						}
						w("| %s | %d | %s | %s | %s | %s | %s | %.0f | %d | %s..%s | %s |\n", opTitles[op], conc, res.Backend,
							fmtMs(m.Median.P50Ms), fmtMs(m.Median.P95Ms), fmtMs(m.Median.P99Ms), fmtMs(m.Median.MeanMs), m.Median.Throughput, m.Median.Errors,
							fmtMs(m.P50RangeMs[0]), fmtMs(m.P50RangeMs[1]), correctnessText(op, t))
					}
				}
			}
		}
		for _, res := range r.Results {
			if res.Dim != dim {
				continue
			}
			if res.Failure != "" {
				w("\n**%s D=%d failed:** %s\n", res.Backend, dim, res.Failure)
			}
			if res.Preload != nil {
				s := res.Preload.Summary
				w("\n- %s preload (%s): %d adds at concurrency %d, %.0f ops/s, p50 %s ms, p99 %s ms, errors %d. CreateNamespace took %s ms.",
					res.Backend, res.Preload.Note, s.Count, res.Preload.Concurrency, s.Throughput, fmtMs(s.P50Ms), fmtMs(s.P99Ms), s.Errors, fmtMs(res.CreateNamespaceMs))
			}
		}
		w("\n")
	}

	w("\n## Index state when queried\n\n")
	for _, res := range r.Results {
		w("### %s, D=%d (namespace `%s`)\n\n", res.Backend, res.Dim, res.Namespace)
		if res.Ready != "" {
			w("- Steady state: %s\n", res.Ready)
		}
		info := res.StoreInfo
		switch res.Backend {
		case "pgvector":
			if info != nil {
				w("- Rows %v; heap %s, TOAST %s, indexes %s, total %s; embedding attstorage `%v`\n", info["rows"], fmtBytes(info["table_bytes"]), fmtBytes(info["toast_bytes"]), fmtBytes(info["indexes_bytes"]), fmtBytes(info["total_bytes"]), info["embedding_attstorage"])
				if idx, ok := asMapSlice(info["indexes"]); ok {
					for _, i := range idx {
						w("- Index `%v` (%s, options %v): `%v`\n", i["name"], fmtBytes(i["bytes"]), i["reloptions"], i["definition"])
					}
				}
			}
		default:
			if info != nil {
				data, _ := json.Marshal(info)
				w("- `%s`\n", string(data))
			}
		}
		if len(res.Plans) > 0 {
			keys := make([]string, 0, len(res.Plans))
			for k := range res.Plans {
				keys = append(keys, k)
			}
			sort.Strings(keys)
			for _, k := range keys {
				w("\n<details><summary>%s</summary>\n\n```\n%s\n```\n</details>\n", k, res.Plans[k])
			}
		}
		w("\n")
	}

	w("## Every run\n\nVM CPU busy: share of CPU time the machine running the client spent busy during the phase (inside Docker Desktop: the whole VM, databases included; blank where unavailable).\n\n")
	w("| Backend | D | Operation | Conc | Run | p50 | p95 | p99 | mean | ops/s | errors | VM CPU busy | first error |\n|---|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|\n")
	for _, res := range r.Results {
		for _, p := range res.Phases {
			busy := ""
			if p.CPUBusyPct != nil {
				busy = fmt.Sprintf("%.0f%%", *p.CPUBusyPct)
			}
			w("| %s | %d | %s | %d | %d | %s | %s | %s | %s | %.0f | %d | %s | %s |\n", res.Backend, res.Dim, opTitles[p.Op], p.Concurrency, p.Run,
				fmtMs(p.Summary.P50Ms), fmtMs(p.Summary.P95Ms), fmtMs(p.Summary.P99Ms), fmtMs(p.Summary.MeanMs), p.Summary.Throughput, p.Summary.Errors, busy, truncate(p.FirstError, 80))
		}
	}

	w("\n## Method\n\n")
	for _, m := range r.Method {
		w("- %s\n", m)
	}
	return b.String()
}

// The renderer runs both on a live Report and on one decoded from its JSON
// (-render), where typed maps and slices come back as map[string]any / []any.
func asStringMap(v any) (map[string]string, bool) {
	switch m := v.(type) {
	case map[string]string:
		return m, true
	case map[string]any:
		out := make(map[string]string, len(m))
		for k, x := range m {
			out[k] = fmt.Sprint(x)
		}
		return out, true
	}
	return nil, false
}

func asStringSlice(v any) ([]string, bool) {
	switch s := v.(type) {
	case []string:
		return s, true
	case []any:
		out := make([]string, len(s))
		for i, x := range s {
			out[i] = fmt.Sprint(x)
		}
		return out, true
	}
	return nil, false
}

func asMapSlice(v any) ([]map[string]any, bool) {
	switch s := v.(type) {
	case []map[string]any:
		return s, true
	case []any:
		out := make([]map[string]any, 0, len(s))
		for _, x := range s {
			if m, ok := x.(map[string]any); ok {
				out = append(out, m)
			}
		}
		return out, true
	}
	return nil, false
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func orDash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}

func truncate(s string, n int) string {
	s = strings.ReplaceAll(s, "|", "/")
	if len(s) <= n {
		return s
	}
	return s[:n] + "..."
}
